#!/usr/bin/env python3
"""Generates src/game/font_builtin.h: a 1-bit ASCII font for the screens that
are drawn before (or without) a library, such as "no library file" and the
loading bar. Rasterised from Pillow's bundled default font (Aileron, CC0)."""

import os

from PIL import Image, ImageDraw, ImageFont

CELL_W, SIZE = 7, 11
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "game", "font_builtin.h")


def main():
    font = ImageFont.load_default(SIZE)
    images = []
    widths = []
    for code in range(0x20, 0x7F):
        im = Image.new("L", (CELL_W + 4, SIZE * 2), 0)
        ImageDraw.Draw(im).text((0, 0), chr(code), fill=255, font=font)
        images.append(im.point(lambda v: 255 if v >= 96 else 0))
        widths.append(min(CELL_W + 1, max(3, int(round(font.getlength(chr(code)))) + 1)))
    # the cell is exactly as tall as the tallest ascender and the lowest descender need
    boxes = [im.getbbox() for im in images if im.getbbox()]
    top, bottom = min(b[1] for b in boxes), max(b[3] for b in boxes)
    CELL_H = bottom - top
    rows = []
    for im in images:
        glyph = []
        for y in range(top, bottom):
            bits = 0
            for x in range(8):
                if im.getpixel((x, y)):
                    bits |= 0x80 >> x
            glyph.append(bits)
        rows.append(glyph)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("/* Generated by tools/gen_builtin_font.py; do not edit. */\n")
        f.write(f"#define FONT_BUILTIN_H {CELL_H}\n")
        f.write("static const unsigned char font_builtin_width[95] = {" + ", ".join(map(str, widths)) + "};\n")
        f.write(f"static const unsigned char font_builtin_bits[95][{CELL_H}] = {{\n")
        for code, glyph in zip(range(0x20, 0x7F), rows):
            f.write("    {" + ", ".join(f"0x{b:02x}" for b in glyph) + "},\n")
        f.write("};\n")


if __name__ == "__main__":
    main()
